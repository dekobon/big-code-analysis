//! Guards on which files `make self-scan` actually measures.
//!
//! An integration test rather than a `src/` unit test because the
//! root crate's `[package].include` ships everything under `src/` to
//! crates.io, and the sibling crate roots this walks are not in that
//! tarball — a `cargo test` on the published crate would panic on the
//! first missing root.

use std::path::Path;

use big_code_analysis::is_generated;
use walkdir::WalkDir;

/// The line `enums/` (`enums/src/rust.rs`, `enums/templates/`) writes
/// into every Rust module it generates.
const CODEGEN_MARKER_LINE: &str = "// Code generated; DO NOT EDIT.";

/// The first line `big-code-analysis-py/src/codegen.rs` and
/// `types_codegen.rs` write into `_enums.py` and `_types.py`.
const PY_CODEGEN_MARKER_LINES: &[&str] = &[
    "# @generated by `big-code-analysis-py` from the live `LANG` / `Metric`",
    "# @generated by `big-code-analysis-py` from the `big_code_analysis::wire`",
];

/// Everything the self-scan *gates* (`bca.toml` `paths = ["."]` minus
/// `.bcaignore` and `[check] exclude`), as `(root, extension, the
/// marker lines its generators write)`. Walking only these keeps
/// `target/`, the Python venv, the corpus submodules, the
/// `[check] exclude`d dev tooling and the test fixtures that
/// legitimately spell a marker out of scope.
const SELF_SCAN_ROOTS: &[(&str, &str, &[&str])] = &[
    ("src", "rs", &[CODEGEN_MARKER_LINE]),
    ("big-code-analysis-ast/src", "rs", &[CODEGEN_MARKER_LINE]),
    ("big-code-analysis-cli/src", "rs", &[CODEGEN_MARKER_LINE]),
    ("big-code-analysis-py/src", "rs", &[CODEGEN_MARKER_LINE]),
    ("big-code-analysis-web/src", "rs", &[CODEGEN_MARKER_LINE]),
    (
        "big-code-analysis-cli/build.rs",
        "rs",
        &[CODEGEN_MARKER_LINE],
    ),
    (
        "big-code-analysis-py/build.rs",
        "rs",
        &[CODEGEN_MARKER_LINE],
    ),
    (
        "big-code-analysis-py/python/big_code_analysis",
        "py",
        PY_CODEGEN_MARKER_LINES,
    ),
];

/// Mirrors `.bcaignore`'s test-scope globs (`./**/tests/**`,
/// `./**/*_tests.rs`, `./**/*_tests/**`, `./**/test_support.rs`);
/// change both. The self-scan never measures these, so a marker quoted
/// in one hides nothing. Not read from `.bcaignore` at runtime, so the
/// test stays dependency-light.
fn self_scan_skips(path: &Path) -> bool {
    path.components().any(|c| {
        let c = c.as_os_str().to_str().unwrap_or_default();
        c == "tests" || c.ends_with("_tests.rs") || c.ends_with("_tests") || c == "test_support.rs"
    })
}

// `is_generated` scans a file's leading window for `@generated` /
// `DO NOT EDIT` / `GENERATED CODE`, case-insensitively, and the gate
// reports a hit only as a count ("1 file not checked (1 generated)").
// So a module doc that merely *quotes* a marker phrase hides its whole
// file from every threshold — `analyze_path` in
// `big-code-analysis-py/src/analysis.rs` was never measured for that
// reason, and `default_thresholds.rs` for the phrase "generated code"
// in a sentence (#1763). Pin that every hit under the self-scan roots
// is a generator's own marker line, so no allowlist has to track the
// generated set.
#[test]
fn no_hand_written_source_quotes_a_generated_marker_in_its_header() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let mut hand_written = Vec::new();
    let mut generated = 0usize;

    for (scan_root, ext, markers) in SELF_SCAN_ROOTS {
        // A traversal error is a failure, not a skipped entry: a renamed
        // root would otherwise drop out of the census while the other
        // roots keep the `generated > 0` guard satisfied.
        let files = WalkDir::new(root.join(scan_root))
            .into_iter()
            .map(|entry| {
                entry
                    .unwrap_or_else(|e| panic!("walking {scan_root} under {}: {e}", root.display()))
            })
            .map(walkdir::DirEntry::into_path)
            .filter(|p| {
                p.is_file() && p.extension().is_some_and(|e| e == *ext) && !self_scan_skips(p)
            });
        for path in files {
            let bytes = std::fs::read(&path)
                .unwrap_or_else(|e| panic!("{} is readable: {e}", path.display()));
            if !is_generated(&bytes) {
                continue;
            }
            let text = std::str::from_utf8(&bytes)
                .unwrap_or_else(|e| panic!("{} is UTF-8 source: {e}", path.display()));
            // The whole-file check matched inside its window, so the
            // first matching line of the file is the line it matched.
            let first_hit = text
                .lines()
                .find(|line| is_generated(line.as_bytes()))
                .expect("a file `is_generated` accepted has a matching line");
            if markers.contains(&first_hit.trim()) {
                generated += 1;
            } else {
                let relative = path.strip_prefix(root).unwrap_or(&path);
                hand_written.push(format!("{}: {first_hit:?}", relative.display()));
            }
        }
    }

    assert!(
        generated > 0,
        "the walk must reach the generated `languages/language_*.rs` modules, \
         or this guard is asserting over nothing"
    );
    assert!(
        hand_written.is_empty(),
        "these hand-written files quote a generated-file marker in the leading \
         window `is_generated` scans, so `make self-scan` silently skips them; \
         rephrase the line so none of `@generated` / `DO NOT EDIT` / \
         `GENERATED CODE` appears there (#1763):\n  {}",
        hand_written.join("\n  ")
    );
}
